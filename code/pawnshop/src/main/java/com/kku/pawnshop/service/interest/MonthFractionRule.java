package com.kku.pawnshop.service.interest;

import java.math.BigDecimal;
import java.time.LocalDate;

/**
 * กฎการนับจำนวนเดือนที่คิดดอกเบี้ย เมื่อระยะเวลามีเศษของเดือน
 *
 * เหตุผลที่แยกออกจาก InterestCalculator (SRP):
 * อัตราดอกเบี้ยเปลี่ยนตามกฎหมาย ส่วนวิธีนับเศษเดือนเป็นธรรมเนียมของร้าน
 * สองอย่างนี้เปลี่ยนคนละเหตุผล จึงต้องเป็นคนละคลาส
 *
 * คลาสนี้เป็นจุดที่ควรเขียน unit test ให้เยอะที่สุดในโปรเจกต์
 * เพราะทดสอบง่าย ไม่ต้องพึ่งฐานข้อมูล และเป็นจุดที่คำนวณผิดแล้วเสียหายจริง
 */
public interface MonthFractionRule {

    /**
     * คืนจำนวนเดือนที่ใช้คิดดอก อาจมีทศนิยมได้ตามธรรมเนียม
     * เช่น เศษไม่เกินครึ่งเดือนคิด 0.5 เดือน เกินครึ่งคิดเต็มเดือน
     */
    BigDecimal chargeableMonths(LocalDate from, LocalDate to);
}
